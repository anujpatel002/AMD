// Creating variables using var

void main() 
{
  
    var x; // Not initialized, so assigned null value.
    print(" x = $x"); // x = null
    print("\n Datatype of x is ${x.runtimeType}");
  
    var n = 100;
    print("\n n = $n");
    print("\n Datatype of n is ${n.runtimeType}");
  
    var firstname = "Akshar";
    print("\n firstname = $firstname");
    print("\n Datatype of firstname is ${firstname.runtimeType}");
  
  
    var weight = 62.50;
    print("\n weight = $weight");
    print("\n Datatype of weight is ${weight.runtimeType}");
  
}
